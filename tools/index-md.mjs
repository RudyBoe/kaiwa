#!/usr/bin/env node
// Rebuild the index table in docs/kaiwa.md from library/*.kaiwa.json, between
// the <!-- index:start --> and <!-- index:end --> markers. Everything else in
// the file (pages, ideas, change log) is left alone.
// Usage: node tools/index-md.mjs           -> rewrite the table
//        node tools/index-md.mjs --check   -> exit 1 if the table is out of date
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DOC = join(ROOT, "docs", "kaiwa.md");
const START = "<!-- index:start -->";
const END = "<!-- index:end -->";

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
// The part of meta after "Beyond L34:", e.g. "none" or "おいしそう (L43)".
const beyond = (meta) => {
  const m = /Beyond L\d+:\s*(.*)$/.exec(meta);
  return m ? m[1].replace(/\.$/, "") : meta;
};

const items = readdirSync(join(ROOT, "library"))
  .filter((f) => f.endsWith(".kaiwa.json"))
  .map((f) => ({ f, d: JSON.parse(readFileSync(join(ROOT, "library", f), "utf8")) }))
  .sort((a, b) => a.d.level.minna_max - b.d.level.minna_max || a.d.created.localeCompare(b.d.created) || a.d.id.localeCompare(b.d.id));

const rows = items.map(({ f, d }) => {
  const extra = [d.curveballs?.length && `${d.curveballs.length} curveballs`, d.questions?.length && `${d.questions.length} questions`].filter(Boolean);
  const size = [`${d.lines.length} lines`, ...extra].join(" + ");
  const roles = d.roles.map((r) => r.en).join(" / ");
  return `| L${d.level.minna_max} | [${cell(d.title)}](../library/${f}) | ${cell(d.subtitle)} | ${d.kind} | ${cell(roles)} | ${size} | ${cell(beyond(d.meta))} | ${d.created} |`;
});
const table = [
  `${items.length} kaiwa, sorted by lesson. Generated by \`node tools/index-md.mjs\`; do not edit by hand.`,
  "",
  "| Up to | Title | Situation | Kind | Roles | Size | Beyond the level | Date |",
  "|---|---|---|---|---|---|---|---|",
  ...rows,
].join("\n");

const doc = readFileSync(DOC, "utf8");
const a = doc.indexOf(START), b = doc.indexOf(END);
if (a < 0 || b < a) { console.log(`FAIL docs/kaiwa.md\n   - needs ${START} and ${END} markers`); process.exit(1); }
const next = doc.slice(0, a + START.length) + "\n" + table + "\n" + doc.slice(b);

if (process.argv.includes("--check")) {
  if (next !== doc) { console.log("FAIL docs/kaiwa.md\n   - index table is out of date: run node tools/index-md.mjs"); process.exit(1); }
  console.log("OK   docs/kaiwa.md index");
} else {
  writeFileSync(DOC, next);
  console.log(`docs/kaiwa.md: ${items.length} kaiwa`);
}
